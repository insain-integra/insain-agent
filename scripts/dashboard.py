"""Собрать docs/dashboard.md из vision, todo и git. Руками файл не править."""

from __future__ import annotations

import re
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DASHBOARD = ROOT / "docs" / "dashboard.md"
TODO = ROOT / "todo"
SKIP_TODO = {"AGENTS.md", "_template.md", "_template-epic.md"}


def _read(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def _git(*args: str) -> str:
    try:
        return subprocess.check_output(
            ["git", *args],
            cwd=ROOT,
            text=True,
            encoding="utf-8",
            errors="replace",
        ).strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return ""


def _status_line(text: str) -> str:
    for ln in text.splitlines():
        if ln.startswith("Статус:"):
            return ln[len("Статус:") :].strip()
    return "?"


def _goal_line(text: str) -> str:
    for ln in text.splitlines():
        if ln.startswith("Цель:") and "должно стать" not in ln:
            return ln[len("Цель:") :].strip()
    return "—"


def forms_counts() -> tuple[int, int, int]:
    """На API, старый JS всего, старый JS на опубликованных страницах."""
    text = _read(ROOT / "docs" / "site" / "forms.md")
    api = old = 0
    for ln in text.splitlines():
        if ln.startswith("| API через"):
            parts = [p.strip() for p in ln.split("|") if p.strip()]
            if len(parts) >= 2 and parts[1].isdigit():
                api = int(parts[1])
        if ln.startswith("| старый JS"):
            parts = [p.strip() for p in ln.split("|") if p.strip()]
            if len(parts) >= 2 and parts[1].isdigit():
                old = int(parts[1])
    pub_old = old
    m = re.search(r"(\d+) из них на опубликованных", text)
    if m:
        pub_old = int(m.group(1))
    return api, old, pub_old


def plugin_version() -> str:
    text = _read(ROOT / "wp-plugin" / "insain-calc-bridge.php")
    m = re.search(r"^\s*\*\s*Version:\s*(\S+)", text, re.M)
    return m.group(1) if m else "?"


def vision_goals() -> list[list[str]]:
    text = _read(ROOT / "docs" / "vision.md")
    rows = []
    for ln in text.splitlines():
        if re.match(r"^\| G\d+ \|", ln):
            cells = [c.strip() for c in ln.strip().strip("|").split("|")]
            if len(cells) >= 6:
                rows.append(cells[:6])
    return rows


def todo_entries() -> tuple[list[tuple[str, str, str]], list[tuple[str, str]]]:
    epics: list[tuple[str, str, str]] = []
    tasks: list[tuple[str, str]] = []
    for path in sorted(TODO.glob("*.md")):
        if path.name in SKIP_TODO:
            continue
        text = _read(path)
        st = _status_line(text)
        if path.name.startswith("EPIC-"):
            epics.append((path.name, _goal_line(text), st))
        else:
            tasks.append((path.name, st))
    return epics, tasks


def last_log_headings(n: int = 5) -> list[str]:
    text = _read(ROOT / "docs" / "history" / "log.md")
    found = [ln[3:] for ln in text.splitlines() if re.match(r"^## \d{4}-\d{2}-\d{2} ", ln)]
    return found[:n]


def snapshot_date() -> str:
    text = _read(ROOT / "docs" / "history" / "snapshots.md")
    m = re.search(r"^## Срез (\d{2}\.\d{2}\.\d{4})", text, re.M)
    return m.group(1) if m else "—"


def status_snapshot_date() -> str:
    text = _read(ROOT / "STATUS.md")
    m = re.search(r"Календарная дата снимка:\s*\*\*([^*]+)\*\*", text)
    return m.group(1).strip() if m else "—"


def _stale(dmy: str, days: int = 14) -> str:
    try:
        d = date(int(dmy[6:10]), int(dmy[3:5]), int(dmy[0:2]))
    except (ValueError, IndexError):
        return ""
    age = (date.today() - d).days
    return " — устарело" if age > days else ""


def render() -> str:
    api, old, pub_old = forms_counts()
    total = api + pub_old
    goals = vision_goals()
    epics, tasks = todo_entries()
    commits = _git("rev-list", "--count", "HEAD") or "?"
    week = _git("rev-list", "--count", "HEAD", "--since=7 days ago") or "?"
    in_work = [n for n, st in tasks if st in {"в работе", "ревью", "доработка", "выкатка", "закрытие"}]
    blocked = [n for n, st in tasks if st.startswith("заблокировано")]
    snap = snapshot_date()
    st_date = status_snapshot_date()
    today = date.today().strftime("%d.%m.%Y")
    log_heads = last_log_headings()

    lines = [
        "<!-- generated by scripts/dashboard.py; не править руками -->",
        "",
        f"# Дашборд insain.ru — {today}",
        "",
        "Собрано из `docs/vision.md`, `todo/`, `docs/site/forms.md`, git. Обновляет",
        "`python scripts/dev.py dashboard` и `python scripts/dev.py close <задача>`.",
        "",
        "## Цели",
        "",
        "| # | Цель | Сейчас | Цель | Срок |",
        "| --- | --- | --- | --- | --- |",
    ]
    for cells in goals:
        num, title, _metric, now, target, deadline = cells
        if num == "G1":
            now = f"{api} из {total} боевых форм"
        lines.append(f"| {num} | {title} | {now} | {target} | {deadline} |")

    lines += [
        "",
        f"G1 по реестру: **{api}** на API, **{pub_old}** старый JS на опубликованных страницах "
        f"(ещё {old - pub_old} без страницы; из `docs/site/forms.md`).",
        "",
        "## Эпики",
        "",
        "| Файл | Цель | Статус |",
        "| --- | --- | --- |",
    ]
    for name, goal, st in epics:
        lines.append(f"| `{name}` | {goal} | {st} |")

    lines += [
        "",
        "## Задачи",
        "",
        f"Открытых файлов задач: **{len(tasks)}**. "
        f"В работе/ревью: {', '.join(f'`{n}`' for n in in_work) or 'нет'}. "
        f"Заблокировано: {', '.join(f'`{n}`' for n in blocked) or 'нет'}.",
        "",
        "| Файл | Статус |",
        "| --- | --- |",
    ]
    for name, st in tasks:
        lines.append(f"| `{name}` | {st} |")

    lines += [
        "",
        "## Репозиторий",
        "",
        f"- Коммитов всего: {commits}; за 7 дней: {week}",
        f"- Плагин `insain-calc-bridge`: {plugin_version()} (шапка в git)",
        f"- Срез метрик: {snap}{_stale(snap) if snap[:1].isdigit() else ''}",
        f"- Снимок прода `STATUS.md`: {st_date}",
        "",
        "## Журнал (последние 5)",
        "",
    ]
    for h in log_heads:
        lines.append(f"- {h}")
    if not log_heads:
        lines.append("- —")
    lines.append("")
    return "\n".join(lines)


def write() -> Path:
    text = render()
    DASHBOARD.write_text(text, encoding="utf-8", newline="\n")
    return DASHBOARD


def check() -> None:
    current = DASHBOARD.read_text(encoding="utf-8") if DASHBOARD.is_file() else ""
    expected = render()
    if current.replace("\r\n", "\n") != expected:
        sys.stderr.write(
            "docs/dashboard.md устарел. Запустите: python scripts/dev.py dashboard\n"
        )
        raise SystemExit(1)


if __name__ == "__main__":
    if "--check" in sys.argv:
        check()
    else:
        path = write()
        print(path)
